// One number style per interface language: spaces between thousands in all three, a decimal comma in UZ and RU,
// a decimal point in EN.
const formatters = {};
function numberFormatter(lang) {
  return (value, digits = 2) => {
    if (typeof value !== "number" || !Number.isFinite(value)) return value == null ? "—" : String(value);
    formatters[digits] ??= new Intl.NumberFormat("ru-RU", { maximumFractionDigits: digits });
    const text = formatters[digits].format(value);
    return lang === "en" ? text.replace(",", ".") : text;
  };
}

